"""Markdown and JSON export for jetlag-forge."""

import json
from datetime import datetime

from . import circadian as C


def to_markdown(report):
    """Render a report as a Markdown briefing."""
    meta = report['meta']
    score = report['score']
    out = []
    out.append('# %s' % (meta['title'] or 'Jet-lag plan'))
    out.append('')
    out.append('**%s** - overall %s/100 (%s)' % (
        meta.get('profile_label', 'Balanced'), score['overall'], score['band_label']))
    out.append('')
    out.append('- Home: %s (%s)' % (meta['home_place'], meta['home_tz']))
    out.append('- Home sleep: %s-%s' % (meta['home_sleep'], meta['home_wake']))
    out.append('- Chronotype: %s' % meta['chronotype'])
    out.append('- Melatonin: %s mg' % (meta['melatonin_mg'] or 'none'))
    if meta.get('purpose'):
        out.append('- Purpose: %s' % meta['purpose'])
    out.append('')

    out.append('## Scorecard')
    out.append('')
    out.append('| Axis | Score | Weight |')
    out.append('| --- | ---: | ---: |')
    for axis in score['axis_order']:
        out.append('| %s | %.1f | %.2f |' % (
            meta['axis_labels'][axis], score['axes'][axis], score['weights'][axis]))
    out.append('| **Overall** | **%.1f** | |' % score['overall'])
    out.append('')
    for axis, reason in score['caps'].items():
        out.append('> **%s cap applied:** %s' % (meta['axis_labels'].get(axis, axis), reason))
    if score['caps']:
        out.append('')

    out.append('## Flights')
    out.append('')
    out.append('| Route | Departure (local) | Arrival (local) | Duration | Shift | Direction |')
    out.append('| --- | --- | --- | ---: | ---: | --- |')
    for leg in report['legs']:
        out.append('| %s -> %s | %s | %s | %sh | %s | %s |' % (
            leg['origin'], leg['dest'], leg['dep_local'], leg['arr_local'],
            leg['duration_h'], C.format_hours(leg['effective_shift_h']),
            leg['direction']))
    out.append('')

    for stay in report['stays']:
        out.append('## %s' % stay['place'])
        out.append('')
        out.append('Shift %s, about %d nights to fully re-enter the local clock, %d nights booked.' % (
            C.format_hours(stay['effective_shift_h']), stay['nights_to_sync'], stay['nights']))
        out.append('')
        out.append('| Date | Body clock at noon | Bed | Wake | Sleep | Light | Caffeine cutoff |')
        out.append('| --- | --- | --- | --- | ---: | --- | --- |')
        for d in stay['days']:
            out.append('| %s | %s | %s | %s | %sh | %s-%s | %s |' % (
                d['date'], d['body_clock_at_noon'],
                d['recommended_bed_local'], d['recommended_wake_local'],
                d['actual_sleep_h'],
                C.format_clock(d['light']['bright_start'])[0],
                C.format_clock(d['light']['bright_end'])[0],
                C.format_clock(d['caffeine']['cutoff'])[0]))
        out.append('')

    if report['events']:
        out.append('## Critical events')
        out.append('')
        out.append('| Event | When (local) | Body clock | Alertness | Verdict |')
        out.append('| --- | --- | --- | ---: | --- |')
        for ev in report['events']:
            out.append('| %s | %s | %s | %.0f | %s |' % (
                ev['name'], ev['when_local'], ev['body_clock_time'],
                ev['alertness'], ev['verdict']))
        out.append('')
        for ev in report['events']:
            out.append('- **%s** (%s): %s' % (ev['name'], ev['when_local'], ev['advice']))
        out.append('')

    out.append('## Findings')
    out.append('')
    for f in report['findings']:
        out.append('### [%s] %s' % (f['severity'].upper(), f['title']))
        out.append('')
        out.append('- **Evidence:** %s' % f['evidence'])
        out.append('- **Why it matters:** %s' % f['why'])
        out.append('- **Fix:** %s' % f['fix'])
        out.append('')

    out.append('## Fix plan')
    out.append('')
    for step in report['plan']:
        out.append('%d. **%s** - %s' % (step['step'], step['when'], step['action']))
        out.append('   - %s' % step['why'])
    out.append('')

    out.append('---')
    out.append('')
    out.append('Generated by jetlag-forge. The circadian model is a two-process approximation '
               '(homeostatic sleep pressure plus circadian alerting) calibrated to published '
               'phase-shift and adaptation rates. It is a planning aid, not medical advice. '
               'Discuss melatonin and any sleep disorder with a clinician.')
    return '\n'.join(out)


def to_json(report):
    return json.dumps(report, indent=2, sort_keys=True, default=str)
